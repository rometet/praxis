target("PraxisCompanion")
    set_kind("shared")
    set_basename("PraxisCompanion")
    set_symbols("debug")
    add_rules("@levibuildscript/linkrule")
    add_rules("@levibuildscript/modpacker", {modVersion = "0.1.0", modPlatform = "client"})
    add_includedirs("src", "src/vendor/kiero")
    add_files("src/Mod.cpp", "src/runtime/Runtime.cpp", "src/MemoryOperators.cpp")
    add_files("src/platform/Native.cpp", "src/platform/EffectPatches.cpp")
    add_files("src/render/WorldOverlays.cpp", "src/render/LightOverlay.cpp", "src/render/RedstoneOverlay.cpp", "src/render/ShulkerPreview.cpp")
    add_files("src/gui/GuiBridge.cpp", "src/gui/GuiBackendCoordinator.cpp", "src/gui/StandaloneGuiHost.cpp", "src/gui/LegacyUiFont.cpp", "src/font/CorporateLogoFont.cpp", "src/vendor/kiero/kiero.cpp")
    add_files("src/resources/praxis_companion.rc")
    add_packages("levilamina", "imgui")
    add_syslinks("user32", "dxgi", "d3d11", "d3d12", "delayimp")
    on_config(function (target)
        import("core.project.config")
        assert(target:is_plat("windows") and target:is_arch("x64"), "PraxisCompanion requires Windows x64")
        assert(config.get("target_type") == "client", "PraxisCompanion is a client-only mod")
    end)
    after_build(function (target)
        local package_dir = path.join(os.projectdir(), "bin", target:name())
        os.mkdir(package_dir)
        for _, name in ipairs({"README.md", "config.example.json"}) do
            os.cp(path.join(os.projectdir(), name), path.join(package_dir, name))
        end
        for _, name in ipairs({"LICENSE", "THIRD_PARTY_NOTICES.md"}) do
            os.cp(path.join(os.projectdir(), name), path.join(package_dir, name))
        end
        os.cp(path.join(os.projectdir(), "licenses"), package_dir)
    end)
target_end()
